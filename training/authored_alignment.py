def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("output", type=Path)
    ap.add_argument("--exclude", type=Path, required=True)
    a = ap.parse_args()
    a.output.mkdir(parents=True, exist_ok=True)
    excluded = [normalized(x["prompt"]) for x in json.loads(a.exclude.read_text(encoding="utf-8"))]
    rows, seen, counts = [], set(), Counter()

    def add(p, r, family, kind):
        identity = (normalized(p), normalized(r))
        if identity in seen or near_eval(p, excluded) or response_rejection(p, r):
            return
        seen.add(identity)
        rows.append({"id": hashlib.sha256((p + '\n' + r).encode()).hexdigest()[:24],
                     "prompt": p, "response": r, "family": family, "source": kind})
        counts[kind] += 1

    for game, strength, weakness, activity in GAMES:
        for index, (p, r) in enumerate(GAME_PATTERNS):
            values = dict(g=game, s=strength, w=weakness, a=activity)
            add(p.format(**values), r.format(**values), f"game-intent-{index}", "authored-game-alignment")
    for index, (prompts, responses) in enumerate(SIMPLE):
        for p in prompts:
            for r in responses:
                add(p, r, f"simple-{index}", "authored-simple-alignment")
    for topic, statement, response in REACTIONS:
        for opening in ["", "По-моему, ", "Мне кажется, ", "Серьёзно, ", "Честно говоря, "]:
            add(opening + (statement if not opening else statement[0].lower() + statement[1:]),
                response, "reaction-" + topic, "authored-reaction-alignment")
    random.Random(20260905).shuffle(rows)
    with (a.output / "authored.jsonl").open("w", encoding="utf-8") as out:
        for row in rows:
            out.write(json.dumps(row, ensure_ascii=False) + "\n")
    report = {"counts": dict(counts), "pairs": len(rows), "unique_prompts": len({normalized(r['prompt']) for r in rows}),
        "game_entities": len(GAMES), "game_intent_templates": len(GAME_PATTERNS),
        "simple_families": len(SIMPLE), "reaction_anchors": len(REACTIONS),
        "provenance": "Codex-authored anchors with explicit template expansion; not independent teacher generation",
        "exclusion": "Exact normalized + lexical near duplicates of development and final prompts excluded"}
    (a.output / "authored-stats.json").write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
